def plot_zebra_calibration(signal: np.ndarray, debug: dict) -> None:
    """Three-panel diagnostic: raw signal + edges, spacing comparison, residuals."""
    signal      = np.asarray(signal, dtype=np.float64)
    edges_px    = debug["edges_px"]
    edges_undist = debug["edges_undistorted_px"]

    fig, axs = plt.subplots(3, 1, figsize=(10, 10))

    axs[0].plot(signal, color="black", lw=1.0, label="Сигнал")
    for x in edges_px:
        axs[0].axvline(x, color="red", alpha=0.2)
    axs[0].set_title("Исходный сигнал (с коррекцией виньетирования) и фронты")
    axs[0].grid(True)
    axs[0].legend()

    axs[1].plot(np.diff(edges_px),    "o-", color="red",   label="До коррекции")
    axs[1].plot(np.diff(edges_undist), "x-", color="green", label="После коррекции")
    axs[1].set_title(f"Межфронтовые расстояния T_ср. = {np.diff(edges_undist).mean():.2f} px")
    axs[1].set_ylabel("px")
    axs[1].grid(True)
    axs[1].legend()

    axs[2].plot(debug["residual_px"], "o-", color="purple")
    axs[2].axhline(0.0, color="gray", lw=1.0)
    axs[2].set_title(f"Остатки RMS = {debug['rms_px']:.4f} px")
    axs[2].set_xlabel("Номер фронта")
    axs[2].set_ylabel("px")
    axs[2].grid(True)

    plt.tight_layout()

